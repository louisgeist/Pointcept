"""
Batch-generate 10-seed GridProbe ensemble configs under
configs/experiment/w110/2/grid_seed_{h3d,eclair,dales}/ from the existing
12-probe lr-grid GridProbeSegmentorV2 reference configs, fixing lr at each
(model, dataset)'s already-established sweep winner.

Mirrors tools/gen_flair3d_mono_configs.py's batch-regeneration pattern: a
small per-row table drives a text transform applied to each reference file,
rather than hand-writing ~27 near-duplicate configs.

Transform applied to every reference file's raw text:
  1. Replace the probes-defining block (from `_losses = {`/`_criteria = [`
     through the last `del ...` line) with a flat 10-probe
     `ce_lovasz_init{i}` dict at the fixed lr (same pattern already applied
     by hand to configs/dales/sonata-v1m2-dales-lin-grid.py this session).
  2. Replace the `wandb_run_name` f-string: "GridProbe" -> "SeedEnsemble",
     "{len(probes)} probes" -> "{len(probes)} inits, lr=<lr>".
  3. Replace the hooks tail: GridProbeWinnerSelector -> GridProbeSeedEnsembleTester.
  4. Insert `test = dict(type="GridProbeSemSegTester", verbose=True)` after hooks.
  5. Fix `_base_`, `grp_exp`, `num_exp` for the new file's location.
  6. Prepend a short docstring note describing the seed-ensemble conversion.

Run once: `python tools/gen_grid_seed_configs.py`. Idempotent (overwrites its
own output files only).
"""

