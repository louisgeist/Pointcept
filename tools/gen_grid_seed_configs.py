def transform(text: str, *, lr: float, num_exp: int) -> str:
    m = PROBES_BLOCK_RE.search(text)
    assert m, "probes block markers not found — reference file shape changed?"

    # Recover the wandb_run_name f-string body (between the opening "(" this
    # regex stopped at and its own closing ")") so we can reuse it, tweaked.
    wandb_start = text.index("wandb_run_name = (", m.start())
    wandb_close = text.index("\n)\n", wandb_start) + len("\n)\n")
    wandb_body = text[wandb_start + len("wandb_run_name = (") : wandb_close - len("\n)\n")]
    wandb_body = wandb_body.replace("GridProbe ", "SeedEnsemble ")
    wandb_body = re.sub(
        r"\{len\(probes\)\} probes", f"{{len(probes)}} inits, lr={lr!r}", wandb_body
    )

    new_block = build_probes_block(lr) + wandb_body + "\n)\n"
    text = text[: m.start()] + "\n" + new_block + text[wandb_close:]

    hm = HOOKS_TAIL_RE.search(text)
    assert hm, "hooks tail (GridProbeWinnerSelector) not found"
    text = (
        text[: hm.start()]
        + 'dict(type="GridProbeSeedEnsembleTester"),\n]'
        + text[hm.end() :]
    )

    # Insert `test = ...` right after the hooks list's closing "]".
    hooks_close = text.index("]", hm.start()) + 1
    insert = (
        "\n\n# Override default_runtime.py's test = dict(type=\"SemSegTester\", ...): the\n"
        "# seed-ensemble test pass needs the shared-backbone, all-probes-at-once tester.\n"
        'test = dict(type="GridProbeSemSegTester", verbose=True)'
    )
    text = text[:hooks_close] + insert + text[hooks_close:]

    # The reference files' top-level `lr = 5e-2` is a dummy/leftover value never
    # actually consumed by the lr-grid (the sweep read lr from _lrs instead) —
    # but it reads as "the lr" and caused exactly that confusion once already
    # this session. Point it at the real fixed value so it can't mislead again.
    text = re.sub(
        r"^lr = [^\n#]+$",
        f"lr = {lr!r}  # fixed at the lr-grid sweep winner (see docstring)",
        text,
        count=1,
        flags=re.MULTILINE,
    )
    text = re.sub(r'^_base_ = \[.*\]$', f'_base_ = ["{OUT_BASE}"]', text, count=1, flags=re.MULTILINE)
    text = re.sub(r"^grp_exp = \d+$", "grp_exp = 2", text, count=1, flags=re.MULTILINE)
    text = re.sub(r"^num_exp = \d+$", f"num_exp = {num_exp}", text, count=1, flags=re.MULTILINE)
    text = re.sub(r'^"""\n', '"""\n' + DOCSTRING_NOTE, text, count=1)
    return text


def read_ref(ref: str) -> str:
    """`ref` is either a repo-relative path (read from the working tree) or
    "git:HEAD:<path>" (read from git history — used for
    configs/dales/sonata-v1m2-dales-lin-grid.py, whose working-tree copy is
    already the hand-converted seed-ensemble from earlier this session)."""
    if ref.startswith("git:"):
        _, rev, path = ref.split(":", 2)
        return subprocess.run(
            ["git", "show", f"{rev}:{path}"], cwd=REPO_ROOT, capture_output=True, text=True, check=True
        ).stdout
    return (REPO_ROOT / ref).read_text()


